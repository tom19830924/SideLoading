"""Package a tagged build and generate the matching personal-tap formula."""
import argparse
import hashlib
from pathlib import Path
import plistlib
import re
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parents[1]
CLI_FILES = ("resign_ipa", "Runtime", "Resources", "README.md", "LICENSE", "requirements-runtime.lock")


def release_version(tag, root=ROOT):
    if not re.fullmatch(r"v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", tag):
        raise ValueError("Release tags must use vMAJOR.MINOR.PATCH, for example v0.3.0.")
    version = tag[1:]
    with (root / "SideLoading/Info.plist").open("rb") as stream:
        configured = plistlib.load(stream)["CFBundleShortVersionString"]
    if configured != version:
        raise ValueError(f"Tag {tag} does not match App version {configured}.")
    return version


def formula(version, sha256):
    return f'''# Generated by SideLoading's release workflow.
class ResignIpa < Formula
  desc "Re-sign iOS IPA archives with your certificate and provisioning profiles"
  homepage "https://github.com/tom19830924/SideLoading"
  url "https://github.com/tom19830924/SideLoading/releases/download/v{version}/resign-ipa-{version}-macos-arm64.tar.gz"
  sha256 "{sha256}"
  version "{version}"
  license "MIT"

  depends_on arch: :arm64
  depends_on macos: :sonoma

  # The bundled runtime is already relocatable and signed by the release build.
  preserve_rpath
  skip_clean "libexec/Runtime"

  def install
    libexec.install "resign_ipa", "Runtime", "Resources", "README.md", "LICENSE", "requirements-runtime.lock"
    bin.install_symlink libexec/"resign_ipa"
  end

  test do
    assert_match "--ipa", shell_output("#{{bin}}/resign_ipa --help")
    assert_match '"type": "result"', shell_output("#{{bin}}/resign_ipa --json environment")
  end
end
'''


def package(tag, root=ROOT):
    version = release_version(tag, root)
    app, cli = root / "SideLoading.app", root / "dist/SideLoadingCLI"
    with (app / "Contents/Info.plist").open("rb") as stream:
        if plistlib.load(stream)["CFBundleShortVersionString"] != version:
            raise ValueError("Built App version does not match the release tag.")
    for name in CLI_FILES:
        if not (cli / name).exists():
            raise ValueError(f"CLI distribution is missing {name}.")
    if (app / "Contents/Resources/LICENSE").read_bytes() != (root / "LICENSE").read_bytes():
        raise ValueError("Built App is missing the current license.")
    output = root / "dist/release"
    output.mkdir(parents=True, exist_ok=True)
    archive = output / f"resign-ipa-{version}-macos-arm64.tar.gz"
    app_zip = output / f"SideLoading-{version}-macos-arm64.zip"
    with tarfile.open(archive, "w:gz") as target:
        for name in CLI_FILES:
            target.add(cli / name, arcname=f"SideLoadingCLI/{name}")
    subprocess.run(["/usr/bin/ditto", "-c", "-k", "--sequesterRsrc", "--keepParent", str(app), str(app_zip)], check=True)
    checksums = {}
    for path in (archive, app_zip):
        with path.open("rb") as stream:
            checksums[path.name] = hashlib.file_digest(stream, "sha256").hexdigest()
    (output / "SHA256SUMS").write_text("".join(f"{digest}  {name}\n" for name, digest in checksums.items()))
    (output / "resign-ipa.rb").write_text(formula(version, checksums[archive.name]))
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tag")
    parser.add_argument("--check", action="store_true", help="Validate the tag and source version without packaging")
    args = parser.parse_args()
    try:
        if args.check:
            print(release_version(args.tag))
        else:
            print(package(args.tag))
    except (ValueError, OSError) as error:
        parser.exit(1, f"Release preparation failed: {error}\n")


if __name__ == "__main__":
    main()
